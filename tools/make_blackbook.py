"""Write js/data/blackbook-pack.js — the Blackbook: hunting doctrine, adversary plays with hunts in several query
languages, the APT casebook, the underground, how cybercriminals were caught, and OSINT tradecraft.

    python tools/make_blackbook.py

The sources are in tools/blackbook/*.py (raw strings, so queries keep their backslashes and quotes exactly).
Every Sigma rule gets a stable id and must come with a proof: an event it matches and one it must not
(tests/blackbook.spec.js runs both through the app's own Sigma engine). Python 3, standard library only.
"""
import json, pathlib, sys, uuid

root = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(root / 'tools' / 'blackbook'))
from doctrine import DOCTRINE, MIRROR
from plays_a import PLAYS_A
from plays_b import PLAYS_B
from plays_c import PLAYS_C
from intel import APT, UNDERGROUND, CAUGHT, CAUGHT_PATTERNS, OSINT

SECTIONS = [
  ('surface', 'Your attack surface', 'globe', 'What a penetration tester or bug-bounty hunter checks first — and the same checks run against yourself.'),
  ('access', 'Initial access', 'log-in', 'How intruders get the first foothold today: stolen sessions, consent, the help desk, the user’s own hands.'),
  ('exec', 'Execution', 'terminal', 'Running code with what Windows already has.'),
  ('persist', 'Persistence', 'anchor', 'Staying after a reboot, a password reset or a patch.'),
  ('evade', 'Stealth and defence impairment', 'eye-off', 'Hiding in trusted processes, blinding the logs and the EDR — and the traces that leaves. (ATT&CK split Defense Evasion into Stealth and Defense Impairment in 2026.)'),
  ('cred', 'Credential access', 'key-round', 'The choke point: almost every intrusion needs someone else’s credentials.'),
  ('disc', 'Discovery', 'radar', 'The first minutes on a new host.'),
  ('lateral', 'Lateral movement', 'network', 'From one machine to the domain.'),
  ('c2', 'Command and control', 'wifi', 'Calling home without looking like it.'),
  ('impact', 'Exfiltration and impact', 'flame', 'The theft before the ransom note, and the last warning before encryption.'),
  ('cloud', 'Identity and cloud', 'cloud', 'Tenants, apps, federation and the control plane.'),
  ('linux', 'Linux and containers', 'server', 'Servers, appliances and clusters.'),
]
LANGS = {'kql': 'KQL — Microsoft Defender XDR / Sentinel', 'spl': 'SPL — Splunk', 'sigma': 'Sigma', 'eql': 'EQL — Elastic',
         'osq': 'osquery', 'cli': 'Commands — triage and hardening'}

def check_play(p, secs):
  need = {'id', 'sec', 't', 'att', 'sev', 'lens', 'sig', 'logs', 'q', 'fp', 'fix'}
  miss = need - set(p)
  assert not miss, (p.get('id'), miss)
  assert p['sec'] in secs, p['id']
  assert p['sev'] in ('low', 'medium', 'high', 'critical'), p['id']
  assert set(p['q']) <= set(LANGS) and p['q'], p['id']
  if 'sigma' in p['q']:
    assert p.get('ev') and len(p['ev']) == 2, p['id'] + ': a Sigma rule needs a matching and a non-matching event'
    s = p['q']['sigma']
    assert s.startswith('title: ') and '\ndetection:\n' in s and '  condition: ' in s, p['id']

def sigma_with_id(p):
  s = p['q']['sigma']
  rid = str(uuid.uuid5(uuid.NAMESPACE_URL, 'osintrix:blackbook:' + p['id']))
  first, rest = s.split('\n', 1)
  extra = 'id: ' + rid + '\n'
  if 'author:' not in rest: extra += 'author: OSINTrix Blackbook\n'
  if 'references:' not in rest: extra += 'references:\n  - https://attack.mitre.org/techniques/' + p['att'][0].replace('.', '/') + '/\n'
  return first + '\n' + extra + rest

def main():
  secs = [s[0] for s in SECTIONS]
  plays = PLAYS_A + PLAYS_B + PLAYS_C
  ids = [p['id'] for p in plays]
  assert len(ids) == len(set(ids)), 'duplicate play id'
  for p in plays:
    check_play(p, secs)
    if 'sigma' in p['q']: p['q']['sigma'] = sigma_with_id(p)
  for a in APT: assert all(x in ids for x in a['plays']), a['id']
  for m in MIRROR: assert m[3] in ids, m
  data = {
    'v': 1,
    'sections': [{'id': s[0], 'title': s[1], 'icon': s[2], 'lead': s[3]} for s in SECTIONS],
    'langs': LANGS,
    'doctrine': [list(x) for x in DOCTRINE],
    'mirror': [list(x) for x in MIRROR],
    'plays': plays,
    'apt': APT,
    'underground': UNDERGROUND,
    'caught': CAUGHT,
    'caughtPatterns': [list(x) for x in CAUGHT_PATTERNS],
    'osint': OSINT,
  }
  body = ('/* The Blackbook — hunting doctrine, adversary plays with hunts (KQL, SPL, Sigma, EQL, osquery), the APT casebook,\n'
          '   working the underground, how cybercriminals were caught, and OSINT tradecraft. Defensive: detection, hunting and\n'
          '   investigation, no exploit code. Generated by tools/make_blackbook.py from tools/blackbook/ — edit there. */\n'
          'const BLACKBOOK = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n')
  (root / 'js' / 'data' / 'blackbook-pack.js').write_text(body, encoding='utf-8', newline='\n')
  n_q = sum(len(p['q']) for p in plays)
  print(f"{len(plays)} plays, {n_q} hunts ({sum('sigma' in p['q'] for p in plays)} Sigma), {len(APT)} APT cases, {len(CAUGHT)} caught cases, "
        f"{sum(len(g['pts']) for g in UNDERGROUND)} underground points, {sum(len(g['pts']) for g in OSINT)} OSINT points, {len(body)//1024} KB")

if __name__ == '__main__':
  main()
