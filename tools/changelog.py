"""Generate CHANGELOG.md from the single source of truth, js/data/changelog.js.

The in-app "What's new" page and this file read the same data, so they never drift.
Edit js/data/changelog.js, then run:

    python tools/changelog.py        ->  CHANGELOG.md

Output follows the "Keep a Changelog" convention (keepachangelog.com):
one section per version, grouped Added / Changed / Fixed / Removed.
Python 3, standard library only.
"""
import json, re, pathlib, datetime

root = pathlib.Path(__file__).resolve().parent.parent
src = (root / 'js' / 'data' / 'changelog.js').read_text(encoding='utf-8')

# pull the JSON array that follows "const CHANGELOG_DATA ="
start = src.index('[')
depth, i = 0, start
for i in range(start, len(src)):
    if src[i] == '[':
        depth += 1
    elif src[i] == ']':
        depth -= 1
        if depth == 0:
            break
data = json.loads(src[start:i + 1])

ORDER = [('added', 'Added'), ('changed', 'Changed'), ('fixed', 'Fixed'), ('removed', 'Removed')]

out = []
out.append('# Changelog')
out.append('')
out.append('All notable changes to OSINTrix, newest first. '
           'The format is based on [Keep a Changelog](https://keepachangelog.com); '
           'this file is generated from `js/data/changelog.js` by `tools/changelog.py`.')
out.append('')

for v in data:
    head = '## [{}]'.format(v['version'])
    if v.get('name'):
        head += ' — {}'.format(v['name'])
    if v.get('date'):
        head += ' ({})'.format(v['date'])
    out.append(head)
    out.append('')
    if v.get('summary'):
        out.append('_{}_'.format(v['summary']))
        out.append('')
    by_type = {}
    for c in v['changes']:
        by_type.setdefault(c['type'], []).append(c['text'])
    for key, label in ORDER:
        if by_type.get(key):
            out.append('### {}'.format(label))
            for text in by_type[key]:
                out.append('- {}'.format(text))
            out.append('')

out.append('---')
out.append('')
out.append('_Generated {} from `js/data/changelog.js`. Do not edit this file by hand — '
           'edit the data file and run `python tools/changelog.py`._'.format(
               datetime.date.today().isoformat()))
out.append('')

(root / 'CHANGELOG.md').write_text('\n'.join(out), encoding='utf-8')
print('CHANGELOG.md  <-  {} versions, {} changes'.format(
    len(data), sum(len(v['changes']) for v in data)))
